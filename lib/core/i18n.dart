import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// Very small translation layer: English text is the key, Swahili is looked
/// up in [_sw]. Anything missing simply stays in English.
class Lang {
  static final notifier = ValueNotifier<String>('en');
  static bool get isSwahili => notifier.value == 'sw';

  static Future<void> load() async {
    try {
      final p = await SharedPreferences.getInstance();
      notifier.value = p.getString('language') ?? 'en';
    } catch (_) {}
  }

  static Future<void> set(String code) async {
    notifier.value = code;
    try {
      final p = await SharedPreferences.getInstance();
      await p.setString('language', code);
    } catch (_) {}
  }
}

/// Translate a UI string.
String tr(String en) => Lang.isSwahili ? (_sw[en] ?? en) : en;

/// Drop-in replacement for Text('…') that follows the app language.
class T extends StatelessWidget {
  final String data;
  final TextStyle? style;
  final TextAlign? textAlign;
  final int? maxLines;
  final TextOverflow? overflow;
  final bool? softWrap;
  const T(this.data, {super.key, this.style, this.textAlign, this.maxLines, this.overflow, this.softWrap});

  @override
  Widget build(BuildContext context) => ValueListenableBuilder<String>(
        valueListenable: Lang.notifier,
        builder: (_, __, ___) => Text(tr(data), style: style, textAlign: textAlign, maxLines: maxLines, overflow: overflow, softWrap: softWrap),
      );
}

